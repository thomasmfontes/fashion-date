import fs from "node:fs";
import path from "node:path";
import postgres from "postgres";

function loadEnv() {
  const envPath = path.resolve(process.cwd(), ".env.local");
  if (fs.existsSync(envPath)) {
    const content = fs.readFileSync(envPath, "utf8");
    for (const line of content.split("\n")) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith("#")) continue;
      const idx = trimmed.indexOf("=");
      if (idx > 0) {
        const key = trimmed.slice(0, idx).trim();
        let val = trimmed.slice(idx + 1).trim();
        if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
          val = val.slice(1, -1);
        }
        if (!process.env[key]) {
          process.env[key] = val;
        }
      }
    }
  }
}

loadEnv();

const dbUrl =
  process.env.DATABASE_URL?.trim() ||
  process.env.POSTGRES_URL?.trim() ||
  process.env.SUPABASE_DB_URL?.trim();

if (!dbUrl) {
  console.error("❌ ERRO: DATABASE_URL não encontrada no arquivo .env.local.");
  process.exit(1);
}

const sql = postgres(dbUrl, {
  max: 1,
  connect_timeout: 15,
});

async function runMigration() {
  console.log("🚀 Iniciando migração da nova estrutura no PostgreSQL/Supabase...\n");

  try {
    // 1. Tabela t_participants: adiciona user_type e permite nr_sorte nullable
    console.log("1️⃣ Atualizando t_participants...");
    await sql`
      CREATE TABLE IF NOT EXISTS public.t_participants (
        id_participante BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nr_sorte TEXT,
        nm_participante TEXT NOT NULL,
        nm_loja TEXT NOT NULL DEFAULT '—',
        nr_whatsapp TEXT NOT NULL UNIQUE,
        nm_instagram TEXT NOT NULL,
        user_type TEXT NOT NULL DEFAULT 'lojista',
        st_participante TEXT NOT NULL DEFAULT 'active',
        dt_cadastro TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
    `;
    await sql`ALTER TABLE public.t_participants ALTER COLUMN nr_sorte DROP NOT NULL;`.catch(() => {});
    await sql`ALTER TABLE public.t_participants ADD COLUMN IF NOT EXISTS user_type TEXT NOT NULL DEFAULT 'lojista';`.catch(() => {});
    console.log("   ✅ t_participants pronta.");

    // 2. Tabela t_draw_definitions (Sorteios Gerenciados pelo Admin)
    console.log("2️⃣ Criando tabela t_draw_definitions...");
    await sql`
      CREATE TABLE IF NOT EXISTS public.t_draw_definitions (
        id_sorteio TEXT PRIMARY KEY,
        nm_titulo TEXT NOT NULL,
        nm_premio TEXT NOT NULL,
        target_user_types JSONB NOT NULL DEFAULT '["lojista", "revendedor", "influencer", "visitante"]'::jsonb,
        tem_limite BOOLEAN NOT NULL DEFAULT FALSE,
        nr_limite_maximo INTEGER,
        st_sorteio TEXT NOT NULL DEFAULT 'open',
        dt_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
    `;
    console.log("   ✅ t_draw_definitions pronta.");

    // 3. Tabela t_draw_tickets (Bilhetes Individuais da Carteira)
    console.log("3️⃣ Criando tabela t_draw_tickets...");
    await sql`
      CREATE TABLE IF NOT EXISTS public.t_draw_tickets (
        id_ticket BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_participante BIGINT NOT NULL REFERENCES public.t_participants(id_participante) ON DELETE CASCADE,
        id_sorteio TEXT NOT NULL REFERENCES public.t_draw_definitions(id_sorteio) ON DELETE CASCADE,
        nr_bilhete TEXT NOT NULL,
        dt_inscricao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        CONSTRAINT unq_participante_sorteio UNIQUE(id_participante, id_sorteio),
        CONSTRAINT unq_sorteio_bilhete UNIQUE(id_sorteio, nr_bilhete)
      );
    `;
    console.log("   ✅ t_draw_tickets pronta.");

    // 4. Tabela t_draw_winners (Ganhadores Apurados no Telão)
    console.log("4️⃣ Criando tabela t_draw_winners...");
    await sql`
      CREATE TABLE IF NOT EXISTS public.t_draw_winners (
        id_vencedor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_sorteio TEXT NOT NULL REFERENCES public.t_draw_definitions(id_sorteio) ON DELETE CASCADE,
        id_participante BIGINT NOT NULL REFERENCES public.t_participants(id_participante) ON DELETE CASCADE,
        nr_bilhete TEXT NOT NULL,
        dt_apuracao TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
    `;
    console.log("   ✅ t_draw_winners pronta.");

    // 5. Seeds Iniciais de Sorteios
    console.log("5️⃣ Populando sorteios padrão do evento em t_draw_definitions...");
    await sql`
      INSERT INTO public.t_draw_definitions (id_sorteio, nm_titulo, nm_premio, target_user_types, tem_limite, nr_limite_maximo, st_sorteio)
      VALUES 
        (
          'draw-provador-01', 
          'Provador Fashion', 
          'Provador Fashion', 
          '["lojista", "revendedor"]'::jsonb, 
          FALSE, 
          NULL, 
          'open'
        ),
        (
          'draw-terno-02', 
          'Sorteio Terno de Luxo', 
          'Terno', 
          '["lojista", "revendedor", "influencer", "visitante"]'::jsonb, 
          TRUE, 
          10, 
          'open'
        )
      ON CONFLICT (id_sorteio) DO UPDATE SET
        nm_titulo = EXCLUDED.nm_titulo,
        nm_premio = EXCLUDED.nm_premio,
        target_user_types = EXCLUDED.target_user_types,
        tem_limite = EXCLUDED.tem_limite,
        nr_limite_maximo = EXCLUDED.nr_limite_maximo;
    `;
    console.log("   ✅ Sorteios padrão sincronizados.");

    // 6. RLS & Segurança
    console.log("6️⃣ Configurando permissões RLS...");
    await sql`
      ALTER TABLE public.t_draw_definitions ENABLE ROW LEVEL SECURITY;
      ALTER TABLE public.t_draw_tickets ENABLE ROW LEVEL SECURITY;
      ALTER TABLE public.t_draw_winners ENABLE ROW LEVEL SECURITY;
    `.catch(() => {});

    console.log("\n=======================================================");
    console.log("🎉 MIGRAÇÃO CONCLUÍDA COM 100% DE SUCESSO NO BANCO!");
    console.log("=======================================================\n");
  } catch (err) {
    console.error("\n❌ ERRO DURANTE A MIGRAÇÃO:", err);
    process.exit(1);
  } finally {
    await sql.end();
  }
}

runMigration();
